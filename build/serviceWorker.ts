/**
 * The service worker of the built site (spec 067), as source text: the app opens and works offline
 * after a first visit, and a deploy shows at once when online.
 *
 * - `known`: every file of the build, relative to the base. A cached file not in it is from an
 *   older deploy and goes on activate.
 * - `precache`: the files fetched ahead, at install: all the app may ask for. Those under `assets/`
 *   carry a content hash in their name, so a deploy fetches only what changed.
 * - `fresh`: the precached files without a hash (from `public/`: the favicon, the manifest, the
 *   icons), fetched again at every install, since their name stays when their content changes.
 * - `version` changes with any file of the build; `commit`, the one it was built from, lets
 *   `qa:live` wait for a deploy to be served (spec 068).
 * - The index is network-first: online, a reload always gets the deployed page; offline, the cached one.
 * - Only same-origin GET requests are answered; ipwho.is and the AI assistants go to the network.
 */
export interface ServiceWorkerManifest {
  version: string
  known: string[]
  precache: string[]
  fresh: string[]
  commit: string
}

export function serviceWorkerSource({ version, known, precache, fresh, commit }: ServiceWorkerManifest): string {
  return `// Keireki Craft service worker (spec 067), generated by the build. Version ${version}. Commit ${commit}.
const CACHE = 'keireki-craft'
const SCOPE = self.registration.scope
const INDEX = SCOPE
const KNOWN = new Set(${JSON.stringify(known)}.map((file) => new URL(file, SCOPE).href))
const PRECACHE = ${JSON.stringify(precache)}.map((file) => new URL(file, SCOPE).href)
const FRESH = new Set(${JSON.stringify(fresh)}.map((file) => new URL(file, SCOPE).href))

/** A file from the server, past the HTTP cache; an error answer fails the install, tried again next visit. */
async function download(url) {
  const response = await fetch(url, { cache: 'reload' })
  if (!response.ok) throw new Error(\`\${url}: \${response.status}\`)
  return response
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE)
    const cached = new Set((await cache.keys()).map((request) => request.url))
    const wanted = [INDEX, ...PRECACHE.filter((url) => FRESH.has(url) || !cached.has(url))]
    // Everything is downloaded before anything is stored: a failed install leaves the cache as it was.
    const responses = await Promise.all(wanted.map(download))
    await Promise.all(wanted.map((url, i) => cache.put(url, responses[i])))
    await self.skipWaiting()
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE)
    for (const request of await cache.keys()) {
      if (request.url !== INDEX && !KNOWN.has(request.url)) await cache.delete(request)
    }
    await self.clients.claim()
  })())
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request)
        if (response.ok && new URL(request.url).pathname === new URL(INDEX).pathname) {
          const copy = response.clone()
          event.waitUntil(caches.open(CACHE).then((cache) => cache.put(INDEX, copy)))
        }
        return response
      } catch (error) {
        const cached = await caches.match(INDEX, { ignoreVary: true })
        if (cached) return cached
        throw error
      }
    })())
    return
  }
  event.respondWith((async () => {
    // ignoreVary: a module script asks with an Origin header the install's fetch did not send.
    const cached = await caches.match(request, { ignoreSearch: true, ignoreVary: true })
    if (cached) return cached
    const response = await fetch(request)
    // A file of this deploy missing from the cache (an install cut short) is kept for next time.
    const url = request.url.split(/[?#]/)[0]
    if (response.ok && KNOWN.has(url)) {
      const copy = response.clone()
      event.waitUntil(caches.open(CACHE).then((cache) => cache.put(url, copy)))
    }
    return response
  })())
})
`
}

/** Files of the site the app itself never asks for: the link card and the crawlers' files (spec 066). */
const NOT_FOR_THE_APP = new Set(['og-image.png', 'robots.txt', 'sitemap.xml', 'sw.js'])

/** The files fetched ahead: everything the app may ask for, the country flags included. */
export function precacheOf(known: string[]): string[] {
  return known.filter((file) => !NOT_FOR_THE_APP.has(file))
}
